/**
 * YouTube 视频页提取器，含字幕抓取逻辑（InnerTube 方案）。
 *
 * 与 B 站不同，YouTube 没有公开的字幕接口：
 * - 官方 Data API v3 的 `captions.download` 只有视频所有者能调用；
 * - 页面里的 `ytInitialPlayerResponse` 在 content script 的 isolated world 中读不到，
 *   且 YouTube 是 SPA，切视频后该对象不会更新。
 *
 * 因此这里走 InnerTube：POST `youtubei/v1/player` 按 videoId 现拉播放器数据，
 * 从中取出 `captionTracks`，再请求 timedtext 拿字幕正文。
 * 按当前 URL 的 videoId 现拉，也顺带解决了 SPA 切视频后数据过期的问题。
 *
 * 数据流：
 *   POST youtubei/v1/player { context, videoId }
 *     └─ .captions.playerCaptionsTracklistRenderer.captionTracks[]
 *          └─ GET {baseUrl}&fmt=json3
 *               └─ { events: [{ tStartMs, dDurationMs, segs: [{ utf8 }] }] }
 *
 * 注意：必须在 `youtube.com` 页面上下文中调用（content script），
 * 该接口依赖页面 cookie 与同源，脱离页面直接请求会拿到 `UNPLAYABLE`。
 */

